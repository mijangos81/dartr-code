#!/usr/bin/env Rscript
# build-functions.R -- data for the function tree on the website (docs/index.html).
#
#   Rscript docs/build-functions.R
#
# Reads the static function reference (skills/dartr-code/references/) and the
# grouping table (docs/function-groups.csv), and writes docs/functions.js.
# Run it after regenerating the reference with dartr_ref.R build.
#
# The grouping table is written by hand: one row per function, with the group
# it belongs to and, optionally, other groups it is also shown in (separated
# by ";"). The script stops if a function in the reference has no row, or a
# row names a function that the reference does not have, so a package update
# cannot leave the tree out of step with the reference. Base R only.

args <- commandArgs(trailingOnly = FALSE)
self <- sub("^--file=", "", args[grep("^--file=", args)])
root <- if (length(self)) dirname(dirname(normalizePath(self))) else getwd()
ref_dir <- file.path(root, "skills", "dartr-code", "references")
csv_file <- file.path(root, "docs", "function-groups.csv")
out_file <- file.path(root, "docs", "functions.js")
REF_URL <- "https://github.com/mijangos81/dartr-code/blob/main/skills/dartr-code/references/"

read_utf8 <- function(f) readLines(f, encoding = "UTF-8", warn = FALSE)

# ---- index.md: package, file and versions -----------------------------------
idx <- read_utf8(file.path(ref_dir, "index.md"))
ver_line <- grep("^Generated by .* from: ", idx, value = TRUE)[1]
versions <- sub("[.] Do not edit by hand[.]$", "", sub("^.* from: ", "", ver_line))
ref_date <- sub("^.* on ([0-9-]+) from: .*$", "\\1", ver_line)

index <- list()
pkg <- NA; file <- NA
for (ln in idx) {
  if (grepl("^## ", ln)) {
    pkg <- sub("^## ([^ ]+) .*$", "\\1", ln)
    file <- sub("^.*`([^`]+)`.*$", "\\1", ln)
  } else if (grepl("^- `", ln)) {
    nm <- sub("^- `([^`]+)`.*$", "\\1", ln)
    index[[nm]] <- list(p = pkg, f = file)
  }
}

# ---- one block per function in each reference file ----------------------------
# GitHub's anchor for a heading: lower case, punctuation removed, spaces to "-".
slug <- function(x) gsub(" ", "-", gsub("[^a-z0-9 _-]", "", tolower(x)))

blocks <- list()
for (f in unique(vapply(index, function(e) e$f, ""))) {
  x <- read_utf8(file.path(ref_dir, f))
  heads <- grep("^#{2,3} ", x)
  seen <- character(0)
  for (h in grep("^### ", x)) {
    # a heading is the name, sometimes followed by a tag: "### name  [DEPRECATED]"
    head_text <- sub("^### ", "", x[h])
    nm <- sub("[[:space:]].*$", "", head_text)
    tag <- if (grepl("[", head_text, fixed = TRUE)) tolower(sub("^.*\\[([^]]+)\\].*$", "\\1", head_text)) else ""
    end <- c(heads[heads > h], length(x) + 1)[1] - 1
    body <- if (end > h) x[(h + 1):end] else character(0)
    fence <- grep("^```", body)
    sig <- if (length(fence) >= 2) paste(body[(fence[1] + 1):(fence[2] - 1)], collapse = "\n") else ""
    lead <- body[seq_len(if (length(fence)) fence[1] - 1 else length(body))]
    lead <- trimws(lead[!grepl("^- ", lead)])
    title <- paste(lead[nzchar(lead)], collapse = " ")
    data <- if (any(startsWith(body, "- **Data:** SNP only"))) "SNP"
            else if (any(startsWith(body, "- **Data:** SilicoDArT only"))) "SilicoDArT" else ""
    a <- slug(head_text)
    k <- sum(seen == a); seen <- c(seen, a)
    blocks[[nm]] <- list(t = title, s = sig, d = data, k = tag, a = if (k) paste0(a, "-", k) else a)
  }
}

missing_block <- setdiff(names(index), names(blocks))
if (length(missing_block)) stop("In index.md but with no block in its file: ", paste(missing_block, collapse = ", "))

# ---- the grouping table -------------------------------------------------------
g <- read.csv(csv_file, stringsAsFactors = FALSE, check.names = FALSE, encoding = "UTF-8")
names(g)[1] <- "fn"
g$also_in[is.na(g$also_in)] <- ""
no_group <- setdiff(names(index), g$fn)
unknown <- setdiff(g$fn, names(index))
dup <- unique(g$fn[duplicated(g$fn)])
if (length(no_group)) stop("Add a row to function-groups.csv for: ", paste(no_group, collapse = ", "))
if (length(unknown)) stop("In function-groups.csv but not in the reference: ", paste(unknown, collapse = ", "))
if (length(dup)) stop("More than one row in function-groups.csv for: ", paste(dup, collapse = ", "))
also <- lapply(strsplit(g$also_in, ";", fixed = TRUE), function(v) trimws(v)[nzchar(trimws(v))])
names(also) <- g$fn
bad <- setdiff(unlist(also), g$group)
if (length(bad)) stop("also_in names a group that no function belongs to: ", paste(bad, collapse = ", "))
stages <- unique(g$stage)
by_ci <- function(v) v[order(tolower(v), v)]

# ---- write docs/functions.js ----------------------------------------------------
q <- function(x) {
  x <- gsub("\\", "\\\\", x, fixed = TRUE)
  x <- gsub("\"", "\\\"", x, fixed = TRUE)
  x <- gsub("\n", "\\n", x, fixed = TRUE)
  x <- gsub("\r", "", x, fixed = TRUE)
  x <- gsub("\t", " ", x, fixed = TRUE)
  paste0("\"", x, "\"")
}
arr <- function(v) if (length(v)) paste0("[", paste(q(v), collapse = ", "), "]") else "[]"

out <- c(
  "/* Written by docs/build-functions.R from skills/dartr-code/references and",
  "   docs/function-groups.csv. Do not edit by hand. */",
  "window.DARTR_FUNCTIONS = {",
  paste0("  \"reference_date\": ", q(ref_date), ","),
  paste0("  \"versions\": ", q(versions), ","),
  paste0("  \"ref\": ", q(REF_URL), ","),
  "  \"stages\": ["
)
for (si in seq_along(stages)) {
  groups <- unique(g$group[g$stage == stages[si]])
  out <- c(out, paste0("    {\"name\": ", q(stages[si]), ", \"groups\": ["))
  for (gi in seq_along(groups)) {
    own <- by_ci(g$fn[g$group == groups[gi]])
    extra <- by_ci(g$fn[vapply(also, function(v) groups[gi] %in% v, logical(1))])
    out <- c(out, paste0("      {\"name\": ", q(groups[gi]), ", \"fns\": ", arr(own), ", \"also\": ", arr(extra), "}",
                         if (gi < length(groups)) "," else ""))
  }
  out <- c(out, paste0("    ]}", if (si < length(stages)) "," else ""))
}
out <- c(out, "  ],", "  \"fns\": {")
fns <- by_ci(g$fn)
for (i in seq_along(fns)) {
  nm <- fns[i]; b <- blocks[[nm]]; e <- index[[nm]]
  out <- c(out, paste0("    ", q(nm), ": {\"p\": ", q(e$p), ", \"g\": ", q(g$group[g$fn == nm]),
                       ", \"t\": ", q(b$t), ", \"s\": ", q(b$s), ", \"d\": ", q(b$d), ", \"k\": ", q(b$k),
                       ", \"f\": ", q(e$f), ", \"a\": ", q(b$a), "}", if (i < length(fns)) "," else ""))
}
out <- c(out, "  }", "};")
con <- file(out_file, open = "wb")
writeLines(enc2utf8(out), con, sep = "\n", useBytes = TRUE)
close(con)

cat(sprintf("Wrote %s: %d functions in %d groups, %d shown in a second group.\n",
            out_file, length(fns), length(unique(g$group)), sum(lengths(also) > 0)))
